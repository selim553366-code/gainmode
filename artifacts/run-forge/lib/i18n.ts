export type CopyKey = keyof typeof translations.en;

export function translate(language: Language, key: CopyKey): string {
  return translations[language][key] ?? translations.en[key];
}

export function localeFor(language: Language) {
  return language === 'tr' ? 'tr-TR' : language === 'de' ? 'de-DE' : language === 'fr' ? 'fr-FR' : language === 'es' ? 'es-ES' : 'en-US';
}