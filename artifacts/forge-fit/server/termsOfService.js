function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function normalizeBasePath(basePath) {
  const normalized = String(basePath || '').replace(/^\/+|\/+$/g, '');
  return normalized ? `/${normalized}` : '';
}

